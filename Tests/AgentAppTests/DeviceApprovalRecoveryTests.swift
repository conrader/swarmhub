    @Test(arguments: [false, true])
    func expiredAttemptStaysLockedOnFailedOrInvalidReceipt(invalid: Bool) async throws {
        let identity = try testApprovalIdentity(), endpoint = DeviceEndpoint(identity: identity)
        endpoint.decisionFailure = 503
        let (host, session) = MockHermesProtocol.serve { request in
            if request.url?.lastPathComponent == "receipt" {
                if invalid {
                    let response: [String: Any] = ["request": DeviceApprovalWire.digest(pickerRequestBody(request)),
                        "receipt": NSNull(), "status": "awaiting-owner", "record": [:]]
                    return (200, response)
                }
                return (503, ["error": "TEST receipt unavailable"])
            }
            return endpoint.handle(request)
        }
        defer { session.invalidateAndCancel() }
        let origin = "https://" + host, defaults = isolatedDefaults()
        let settings = DeviceApprovalSettings(defaults: defaults), reviewed = endpoint.operation(origin: origin)
        await #expect(throws: (any Error).self) {
            try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "decide", task: deviceTask,
                input: deviceDecisionInput(reviewed, approved: true), identity: identity, settings: settings,
                reviewed: reviewed, session: session)
        }
        endpoint.receiptTime = endpoint.issued + 61
        let previous = try settings.attempt(origin: origin, task: deviceTask)
        await #expect(throws: (any Error).self) {
            try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "get", task: deviceTask,
                input: nil, identity: identity, settings: DeviceApprovalSettings(defaults: defaults), session: session)
        }
        let retained = try settings.attempt(origin: origin, task: deviceTask)
        #expect(previous != nil && retained == previous)
        #expect(endpoint.calls == ["challenge", "decide"])
    }

    @Test(arguments: ["missing-time", "float-time", "oversized-time", "wrong-runtime", "decided-pending"])
    func expiredAttemptRequiresValidPendingSnapshot(damage: String) async throws {
        let identity = try testApprovalIdentity(), endpoint = DeviceEndpoint(identity: identity)
        endpoint.issued -= 120; endpoint.decisionFailure = 503
        let (host, session) = MockHermesProtocol.serve { request in
            let (status, value) = endpoint.handle(request)
            guard request.url?.lastPathComponent == "receipt", var response = value as? [String: Any],
                  var record = response["record"] as? [String: Any] else { return (status, value) }
            switch damage {
            case "missing-time": response.removeValue(forKey: "observed_at")
            case "float-time": response["observed_at"] = 1.5
            case "oversized-time": response["observed_at"] = Int64(9_007_199_254_740_992)
            case "wrong-runtime":
                record["remoteBinding"] = ["origin": "https://" + request.url!.host!,
                    "runtime": UUID().uuidString.lowercased(), "profile": "owner"]
            default: record["decided_by"] = "owner"; record["decided_at"] = 1020
            }
            response["record"] = record
            return (status, response)
        }
        defer { session.invalidateAndCancel() }
        let origin = "https://" + host, settings = DeviceApprovalSettings(defaults: isolatedDefaults())
        let reviewed = endpoint.operation(origin: origin)
        await #expect(throws: (any Error).self) {
            try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "decide", task: deviceTask,
                input: deviceDecisionInput(reviewed, approved: true), identity: identity, settings: settings,
                reviewed: reviewed, session: session)
        }
        let previous = try settings.attempt(origin: origin, task: deviceTask)
        await #expect(throws: (any Error).self) {
            try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "get", task: deviceTask,
                input: nil, identity: identity, settings: settings, session: session)
        }
        let retained = try settings.attempt(origin: origin, task: deviceTask)
        #expect(previous != nil && retained == previous)
        #expect(endpoint.calls == ["challenge", "decide", "receipt"])
    }

    @Test(arguments: ["signature_invalid", "request_expired", "challenge_limited"])
    func readRefusalsExposeRejectedError(reason: String) async throws {
        let identity = try testApprovalIdentity()
        let (host, session) = MockHermesProtocol.serve { _ in
            (403, ["error": "control request refused", "reason": reason])
        }
        defer { session.invalidateAndCancel() }
        let origin = "https://" + host
        for verb in ["challenge", "receipt"] {
            do {
                _ = try await DeviceApprovalClient.read(verb, origin: origin, profile: "owner", task: deviceTask,
                    identity: identity, session: session, timeout: 1)
                Issue.record("Read must be rejected")
            } catch ManagedControlError.rejected {}
        }
        do {
            _ = try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "get", task: deviceTask,
                input: nil, identity: identity, settings: DeviceApprovalSettings(defaults: isolatedDefaults()), session: session)
            Issue.record("Get must be rejected")
        } catch ManagedControlError.rejected {}
        do {
            _ = try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "decide", task: deviceTask,
                input: nil, identity: identity, settings: DeviceApprovalSettings(defaults: isolatedDefaults()), session: session)
            Issue.record("Challenge refusal must stop dispatch")
        } catch ManagedControlError.unsent(let message) {
            #expect(message == ManagedControlError.rejected.localizedDescription)
        }
    }

    @Test @MainActor func expiredPendingCardClearsChoiceWithoutResending() async throws {
        let seeds = try DeviceApprovalJSON.parse(Data(contentsOf: deviceFixture("release-bundles/TEST-device-keys.json")))
        let seed = approvalHex(try #require(seeds["keys"]?.arrayValue?.first?["seed"]?.stringValue))
        let endpoint = DeviceEndpoint(identity: try DeviceApprovalIdentity(seed: seed))
        endpoint.issued -= 120 // Expired box time stand-in; no waiting or sockets.
        endpoint.decisionFailure = 503
        let (host, session) = MockHermesProtocol.serve { endpoint.handle($0) }
        defer { session.invalidateAndCancel() }
        let origin = "https://" + host, defaults = isolatedDefaults(), keys = MemoryApprovalKeys()
        try keys.insert(seed, account: DeviceApprovalIdentity.account(box: origin))
        let settings = DeviceApprovalSettings(defaults: defaults); settings.confirmOperatorCutover(origin)
        let store = AppStore(storeURL: temporaryStore(), autoConfigureHermes: false, keyStore: InMemoryKeyStore(),
            defaults: defaults, hermesSession: session, approvalKeys: keys)
        let bot = Bot(name: "TEST owner", backend: .hermes, hermesProfile: "owner")
        bot.hermesBaseURL = origin + "/v1"; store.bots = [bot]
        let reviewed = try await store.managedRuntime(bot, verb: "get", task: deviceTask)
        store.approvals = [try reviewed.request(botID: bot.id)]
        store.decideManagedAction(try #require(store.approvals.first), approved: true)
        try await waitUntil { store.approvals.first?.decisionPending == false }
        #expect(store.approvals.first?.managedDecision == true)
        let saved = try StoreFile.decode(JSONEncoder().encode(store.storeFile))
        store.approvals = try #require(saved.managedApprovals)
        store.decideManagedAction(try #require(store.approvals.first), approved: true)
        try await waitUntil { store.approvals.first?.decisionPending == false }
        #expect(store.approvals.first?.managedDecision == nil && store.approvals.count == 1)
        #expect(!settings.hasAttempt(origin: origin, task: deviceTask))
        #expect(bot.approvalAudit.isEmpty)
        #expect(store.errorMessage == ManagedControlError.attemptExpired.localizedDescription)
        #expect(endpoint.calls == ["receipt", "receipt", "challenge", "decide", "receipt"])
        endpoint.issued = Int64(Date().timeIntervalSince1970); endpoint.decisionFailure = nil
        store.decideManagedAction(try #require(store.approvals.first), approved: false)
        try await waitUntil { store.approvals.isEmpty }
        #expect(bot.approvalAudit.last?.outcome == .denied)
        #expect(endpoint.calls == ["receipt", "receipt", "challenge", "decide", "receipt", "receipt", "challenge", "decide"])
    }
