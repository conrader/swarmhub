    @Test(arguments: [408, 503, 403])
    func ambiguousAttemptClearsOnlyAfterExpiryAndFreshPendingReceipt(status: Int) async throws {
        let identity = try testApprovalIdentity(), endpoint = DeviceEndpoint(identity: identity)
        endpoint.decisionFailure = status; endpoint.refusalReason = "TEST-unknown-result"
        let (host, stubSession) = MockHermesProtocol.serve { endpoint.handle($0) }
        let configuration = URLSessionConfiguration.ephemeral
        configuration.protocolClasses = [DeviceDecisionTimeoutProtocol.self, MockHermesProtocol.self]
        let session = status == 408 ? URLSession(configuration: configuration) : stubSession
        defer { session.invalidateAndCancel(); stubSession.invalidateAndCancel() }
        let origin = "https://" + host, defaults = isolatedDefaults()
        let settings = DeviceApprovalSettings(defaults: defaults), reviewed = endpoint.operation(origin: origin)
        await #expect(throws: (any Error).self) {
            try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "decide", task: deviceTask,
                input: deviceDecisionInput(reviewed, approved: true), identity: identity, settings: settings,
                reviewed: reviewed, session: session)
        }
        let restarted = DeviceApprovalSettings(defaults: defaults)
        // A pending read started before expiry must stay locked, even if its reply arrives later.
        endpoint.receiptTime = endpoint.issued + 59
        do {
            _ = try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "get", task: deviceTask,
                input: nil, identity: identity, settings: restarted, session: session)
            Issue.record("A live nonce must stay locked")
        } catch ManagedControlError.rejected {}
        #expect(restarted.hasAttempt(origin: origin, task: deviceTask))
        endpoint.receiptTime = endpoint.issued + 60
        do {
            _ = try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "get", task: deviceTask,
                input: nil, identity: identity, settings: restarted, session: session)
            Issue.record("Recovery must stop before another decision")
        } catch ManagedControlError.attemptExpired {}
        #expect(!restarted.hasAttempt(origin: origin, task: deviceTask))
        #expect(endpoint.calls == (status == 408 ? ["challenge", "receipt", "receipt"] : ["challenge", "decide", "receipt", "receipt"]))
        // Display is available again, with no challenge or decision generated by recovery.
        let current = try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "get", task: deviceTask,
            input: nil, identity: identity, settings: restarted, session: stubSession)
        #expect(current.sameOperation(as: reviewed) && current.awaiting)
        // Only a new explicit choice can send, and it may now be a denial.
        endpoint.decisionFailure = nil
        let denied = try await DeviceApprovalClient.request(address: origin, profile: "owner", verb: "decide", task: deviceTask,
            input: deviceDecisionInput(current, approved: false), identity: identity, settings: restarted,
            reviewed: current, session: stubSession)
        #expect(denied.confirms(false, original: reviewed))
    }

