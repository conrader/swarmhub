// Hermes's own bookkeeping rows fold into one "Internal activity" line. The samples are shaped like Jarvis's rows 4597
// (2026-10-21, Hermes 0.22, typed `async_delegation_complete`) and 4321 (2026-10-14, untyped); the result text is synthetic.

private let batchNote = """
[ASYNC DELEGATION BATCH COMPLETE — deleg_b801d015]
A background fan-out unit you dispatched earlier — 4 subagent(s) — has finished; its consolidated results are below. Any other units from the same delegate_task call report separately as they finish. You may have moved on since dispatching — act on these or re-dispatch if things have changed.

Dispatched: 2026-10-21 12:46:52 (3m 54s ago)
Role: leaf   Model: grok-4.3-fast   Total duration: 234.59s

[1/4] Check the nightly backups on box 1 and box 2: completed (58s)
Both backups finished; box 2 at 08:58.
"""
private let singleNote = """
[ASYNC DELEGATION COMPLETE — deleg_f33976d1]
A background subagent you dispatched earlier has finished. You may have moved on since dispatching it; the full task source is below so you can act on the result or re-dispatch if things have changed.

Dispatched: 2026-10-14 22:06:19 (40s ago)
Original goal: Summarise the open invoices
"""
private let processNote = """
[Background process proc_7f3a2c finished with exit code 0]
Command: ./scripts/backup.sh --box 2
Output (last 3 lines):
backup ok

[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]
"""
private var context: TechnicalContext { TechnicalContext(botName: "Jarvis") }
private let adopted = ["box": "4597", "restored": "added"]

private func fold(_ message: ChatMessage) -> TechnicalFold? { TechnicalRow.classify(message, context: context) }

@Test func theBoxRowKeepsItsDisplayKind() throws {
    let typed = try #require(HermesBackend.parseMessage(["id": 4597, "role": "user", "content": batchNote, "timestamp": 1_792_154_647.0,
                                                         "display_kind": "async_delegation_complete"], toolCalls: true))
    #expect(typed.displayKind == "async_delegation_complete" && typed.content == batchNote)
    let untyped = try #require(HermesBackend.parseMessage(["id": 4321, "role": "user", "content": batchNote, "display_kind": NSNull()]))
    #expect(untyped.displayKind == nil)
    #expect(HermesBackend.parseMessage(["role": "user", "content": "hi", "display_kind": ""])?.displayKind == nil)
}

@Test func aTypedDelegationNoteFoldsIntoAnInternalActivityLine() throws {
    let note = ChatMessage(role: .user, content: batchNote, metadata: adopted.merging([HermesDisplayKey.kind: "async_delegation_complete"]) { $1 })
    let line = try #require(fold(note))
    #expect(line.kind == .internalNote && line.summary == "Internal activity · background tasks finished")
    #expect(line.original == batchNote && note.content == batchNote, "display only: the text stays for unfold, copy and search")
    let process = ChatMessage(role: .user, content: "Process proc_1 finished.", metadata: [HermesDisplayKey.kind: "process_complete"])
    #expect(fold(process)?.summary == "Internal activity · background process finished")
    let generic = ChatMessage(role: .user, content: "Anything", metadata: [HermesDisplayKey.kind: "internal_notification"])
    #expect(fold(generic)?.kind == .internalNote)
}

@Test(arguments: [batchNote, singleNote, "  \n" + batchNote]) func anUntypedRowFromAnOlderHermesFoldsByItsHeader(text: String) throws {
    let line = try #require(fold(ChatMessage(role: .user, content: text, metadata: adopted)))
    #expect(line.kind == .internalNote && line.summary == "Internal activity · background tasks finished")
}

@Test func aNotificationWithTheGatewayFooterFolds() throws {
    let line = try #require(fold(ChatMessage(role: .user, content: processNote, metadata: adopted)))
    #expect(line.kind == .internalNote && line.summary == "Internal activity · Hermes note")
}

@Test(arguments: [
    "Can you check the async delegation results from this morning?",
    "Why did the delegation deleg_b801d015 take 4 minutes?",
    "What does this mean? [ASYNC DELEGATION BATCH COMPLETE — deleg_b801d015]",
    "[ASYNC DELEGATION BATCH COMPLETE] is what I saw, without an id",
    "[ASYNC DELEGATION COMPLETE - deleg_b801d015] with a plain hyphen is not what Hermes writes",
    "Hermes appends \"[INTERNAL NOTIFICATION — generated by the Hermes gateway …]\" to notifications.\nIs that why the bot ignored me?",
    "Please delegate this to Infra and tell me when the delegation is complete.",
]) func aNormalMessageThatMentionsDelegationStillShows(text: String) {
    #expect(fold(ChatMessage(role: .user, content: text, metadata: adopted)) == nil, "\(text)")
    #expect(HermesInternalNote.summary(ChatMessage(role: .user, content: text)) == nil)
}

@Test func botRepliesAndUnknownKindsAreNeverFolded() {
    // A bot's real reply, even one that starts with the header or reports on the delegation, is the bot's own text.
    for text in [batchNote, "The async delegation finished: all four checks passed.", processNote] {
        #expect(fold(ChatMessage(role: .assistant, content: text, metadata: [HermesDisplayKey.kind: "async_delegation_complete"])) == nil)
    }
    // A kind this build does not know (a newer Hermes) or the user's own slash skill displays as before.
    for kind in ["skill_invocation", "future_timeline_event", ""] {
        #expect(fold(ChatMessage(role: .user, content: "Run the weekly report", metadata: [HermesDisplayKey.kind: kind])) == nil, "\(kind)")
    }
    // An attachment row is the user's.
    let attached = ChatMessage(role: .user, content: batchNote, attachments: [ChatAttachment(id: UUID(), kind: .text, name: "note.txt", mimeType: "text/plain", byteCount: 1, text: "x")])
    #expect(HermesInternalNote.summary(attached) == nil)
}

@MainActor @Test func reconcileAdoptsTheNoteFoldedAndTheBotsReplyShows() async throws {
    let (store, bots, states) = reconcileStore(bots: ["Jarvis"])
    let bot = bots[0]; bot.hermesSessionID = "s-jarvis"
    let start = Date().addingTimeInterval(-600)
    states[0].add("s-jarvis", "user", "Check the backups, disks and certificates in parallel.", time: start.timeIntervalSince1970)
    states[0].add("s-jarvis", "assistant", "Dispatched 4 checks; I will report when they are back.", finish: "stop", time: start.addingTimeInterval(5).timeIntervalSince1970)
    states[0].add("s-jarvis", "user", batchNote, time: start.addingTimeInterval(240).timeIntervalSince1970, displayKind: "async_delegation_complete")
    states[0].add("s-jarvis", "assistant", "All four checks are back: backups, disk and certificates are fine.", finish: "stop", time: start.addingTimeInterval(250).timeIntervalSince1970)
    bot.messages = [ChatMessage(role: .user, content: "Check the backups, disks and certificates in parallel.", createdAt: start),
                    ChatMessage(role: .assistant, content: "Dispatched 4 checks; I will report when they are back.", createdAt: start.addingTimeInterval(5), turnState: .finished)]
    await store.reconcile(bot, reason: .refresh)
    #expect(bot.messages.count == 4)
    let note = bot.messages[2], reply = bot.messages[3]
    #expect(note.role == .user && note.content == batchNote && note.metadata[HermesDisplayKey.kind] == "async_delegation_complete")
    let layout = store.technicalLayout(bot.messages, botName: bot.name)
    #expect(layout.folds[note.id]?.kind == .internalNote)
    #expect(layout.folds[reply.id] == nil && layout.visible(bot.messages).contains { $0.id == reply.id }, "the real reply is a normal bubble")
    let preview = SidebarFragment.text(messages: bot.messages, draft: nil, isWorking: false, archiveNewest: nil, technical: context)
    #expect(preview.contains("All four checks are back"))
    // Saved and read back, the kind is still there; a second pass adds nothing.
    let decoded = try JSONDecoder().decode(ChatMessage.self, from: JSONEncoder().encode(note))
    #expect(decoded.metadata[HermesDisplayKey.kind] == "async_delegation_complete")
    await store.reconcile(bot, reason: .refresh)
    #expect(bot.messages.count == 4)
}

@MainActor @Test func mergedHistoryCarriesTheKindToo() throws {
    var row = BackendMessage(role: "user", content: batchNote); row.displayKind = "async_delegation_complete"
    let merged = try #require(AppStore.mergeHermesHistory(local: [], server: [row, BackendMessage(role: "assistant", content: "Done.")]))
    #expect(merged.first?.metadata[HermesDisplayKey.kind] == "async_delegation_complete")
    #expect(merged.last?.metadata[HermesDisplayKey.kind] == nil)
}
