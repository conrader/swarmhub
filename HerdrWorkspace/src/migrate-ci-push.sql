BEGIN IMMEDIATE;
CREATE TABLE ci_push_key (id INTEGER PRIMARY KEY CHECK(id=1), pkcs8 BLOB NOT NULL);
CREATE TABLE ci_push_devices (id INTEGER PRIMARY KEY AUTOINCREMENT, endpoint TEXT NOT NULL UNIQUE);
CREATE TABLE ci_push_queue (
    device INTEGER NOT NULL REFERENCES ci_push_devices(id) ON DELETE CASCADE,
    watch INTEGER NOT NULL REFERENCES bot_checkins(id) ON DELETE CASCADE,
    expires INTEGER NOT NULL, next_try INTEGER NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (device,watch)
);
PRAGMA user_version=85;
COMMIT;
