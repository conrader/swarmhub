"""Text that ops/hb-move installs, rendered from /etc/swarmhub/bots.json: the nginx snippet, the gateway's port drop-in
and the default-profile .env of a bot account. Pure functions; no I/O."""

SNIPPET = "/etc/nginx/snippets/swarmhub-bots.conf"
INCLUDE = f"include {SNIPPET};"

PROXY = """        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;"""


def nginx(registry):
    """One block per registered bot: its gateway (/p/<profile>/), its webhook receiver and its control routes.

    `^~` prefixes beat the site's generic /p/ and /swarmhub/webhook/ locations (longest prefix, no regex check), so
    profiles that stay shared keep their existing routes. The webhook block repeats docs/webhooks-exposure.md: POST
    only, 32k, request buffering on (the receiver refuses Transfer-Encoding), path unchanged, no header logging.
    """
    lines = ["# Generated by ops/hb-move from /etc/swarmhub/bots.json; do not edit by hand.",
             f"# Include it inside the Hermes site's server block: {INCLUDE}", ""]
    for name in sorted(registry["bots"]):
        bot = registry["bots"][name]
        lines += [f"# {name}: account {bot['user']} (uid {bot['uid']})",
                  f"location ^~ /p/{name}/ {{",
                  f"        proxy_pass http://127.0.0.1:{bot['gateway_port']};",
                  "        proxy_http_version 1.1;",
                  '        proxy_set_header Connection "";',
                  PROXY,
                  "        proxy_buffering off;",
                  "        proxy_read_timeout 3600s;",
                  "}",
                  f"location ^~ /swarmhub/webhook/{name}/ {{",
                  "        limit_except POST { deny all; }",
                  "        client_max_body_size 32k;",
                  "        proxy_request_buffering on;",
                  f"        proxy_pass http://127.0.0.1:{bot['receiver_port']};",
                  PROXY,
                  "}"]
        for version in ("v1", "v2"):
            lines += [f"location ^~ /swarmhub/control/{version}/{name}/ {{",
                      f"        proxy_pass http://127.0.0.1:{bot['control_port']};",
                      PROXY,
                      "}"]
        lines.append("")
    return "\n".join(lines)


def dropin(bot):
    """hermes-bot@<instance>.service.d/10-ports.conf."""
    return ("# Generated by ops/hb-move from /etc/swarmhub/bots.json.\n[Service]\n"
            f"Environment=API_SERVER_PORT={bot['gateway_port']}\n")


def default_env(bot, key):
    """The account's own default profile (~/.hermes/.env): the API server on its loopback port with a fresh key.

    The bot's real profile keeps its own .env (and API_SERVER_KEY) under profiles/<name>/, so the app address and key
    stay the same. Nothing from the shared Hermes root (provider logins included) is copied.
    """
    return ("# Written by ops/hb-move. The default profile of this bot's own account.\n"
            "API_SERVER_ENABLED=true\nAPI_SERVER_HOST=127.0.0.1\n"
            f"API_SERVER_PORT={bot['gateway_port']}\nAPI_SERVER_KEY={key}\n")


def plugin_loader(script):
    """The moved profile's plugins/swarmhub-peer/__init__.py, loading its own skill's peer-runtime.py at `script`
    (relative to the profile). The same text as the skill's swarm_control.plugin_loader writes for a skill inside the
    profile, so the profile loads in the bot's account and again after --undo."""
    return ("import os, runpy, sys\n"
            "script = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "
            f"{str(script)!r})\n"
            "sys.path.insert(0, os.path.dirname(script))\n"
            "register = runpy.run_path(script)[\"register\"]\n")
