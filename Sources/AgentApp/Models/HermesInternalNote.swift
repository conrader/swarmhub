import Foundation

/// Hermes's own bookkeeping turns (an async delegation or a background process finishing, a crash-recovery continue, a
/// model or personality switch) are `role: user` rows the gateway wrote, not the user. Hermes 0.22 types them with
/// `display_kind`, kept on the row as `HermesDisplayKey.kind`; rows written before that are untyped, so two fixed Hermes
/// texts are matched as a fallback. The chat folds such a row into one "Internal activity" line (P51; `content` is never
/// rewritten). Only user rows are read, and anything not recognised (a new kind, a changed header) shows as before.
enum HermesInternalNote {
    /// `display_kind` values of rows no human typed. `skill_invocation` (the user's own slash skill) is not one.
    static let kinds: Set<String> = ["async_delegation_complete", "internal_notification", "process_complete", "auto_continue",
                                     "model_switch", "personality_switch", "hidden"]
    /// The header `tools/process_registry` starts a delegation result with: `[ASYNC DELEGATION BATCH COMPLETE — deleg_…]`.
    private static let delegationHeader = try! NSRegularExpression(
        pattern: #"\A\s*\[ASYNC DELEGATION (?:BATCH )?COMPLETE — deleg_[A-Za-z0-9]+\]"#)
    /// The start of the footer line `gateway/run_notifications` appends to a self-injected notification (Hermes #52694).
    static let footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway"

    /// The fold line of a row Hermes wrote itself; nil for every other row.
    static func summary(_ message: ChatMessage) -> String? {
        guard message.role == .user, message.attachments.isEmpty else { return nil }
        if let kind = message.metadata[HermesDisplayKey.kind], kinds.contains(kind) { return label(kind: kind) }
        let text = message.content
        if delegationHeader.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil { return label(kind: "async_delegation_complete") }
        let last = text.split(whereSeparator: \.isNewline).last.map { $0.trimmingCharacters(in: .whitespaces) } ?? ""
        if last.hasPrefix(footer), last.hasSuffix("]") { return label(kind: "internal_notification") }
        return nil
    }

    static func label(kind: String) -> String {
        switch kind {
        case "async_delegation_complete": "Internal activity · background tasks finished"
        case "process_complete": "Internal activity · background process finished"
        case "auto_continue": "Internal activity · interrupted turn resumed"
        case "model_switch": "Internal activity · model switched"
        case "personality_switch": "Internal activity · personality switched"
        default: "Internal activity · Hermes note"
        }
    }
}

/// The box row's `display_kind` (Hermes 0.22+), on a message the reconcile adopted.
enum HermesDisplayKey { static let kind = "hermes.displayKind" }
