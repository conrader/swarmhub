#!/usr/bin/env python3
"""Regenerate the signed release test vectors under Tests/Fixtures/release-bundles/ (CORE-PHASES.md P0a).

    python3 scripts/release/make_vectors.py [--out DIR]     write keys/ channels/ bundles/ blobs/ and vectors.json
    python3 scripts/release/make_vectors.py --check         regenerate in a temp dir and compare byte for byte

All keys are TEST keys from fixed public seeds; output is byte-identical on every run. The script owns only those
four directories and vectors.json; anything else under --out (for example P0d's renders/) is left alone.
"""

import argparse
import filecmp
import json
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from vector_cases import JCS_VECTORS, JCS_ERRORS, build_cases  # noqa: E402

ROOT = HERE.parents[1]
DEFAULT_OUT = ROOT / "Tests/Fixtures/release-bundles"
OWNED = ("keys", "channels", "bundles", "blobs")


def vectors_document(world):
    jcs_cases = [{"id": i, "input": text, "canonical": out} for i, text, out in JCS_VECTORS]
    jcs_cases += [{"id": i, "input": text, "error": True} for i, text in JCS_ERRORS]
    return {
        "schema": "swarmhub/release-vectors/1",
        "note": "Generated by scripts/release/make_vectors.py. TEST keys only. See docs/update-service/SCHEMAS.md.",
        "jcs": jcs_cases,
        "cases": world.cases,
    }


def write(out):
    world = build_cases()
    for name in OWNED:
        shutil.rmtree(out / name, ignore_errors=True)
    for rel, data in sorted(world.files.items()):
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    text = json.dumps(vectors_document(world), indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    (out / "vectors.json").write_text(text, encoding="utf-8")
    return world


def tree(directory):
    paths = [p for name in OWNED for p in (directory / name).rglob("*") if p.is_file()]
    paths.append(directory / "vectors.json")
    return sorted(str(p.relative_to(directory)) for p in paths if p.exists())


def differences(expected, actual):
    left, right = tree(expected), tree(actual)
    diffs = [f"only in regenerated: {p}" for p in sorted(set(left) - set(right))]
    diffs += [f"only in fixtures: {p}" for p in sorted(set(right) - set(left))]
    diffs += [f"differs: {p}" for p in sorted(set(left) & set(right))
              if not filecmp.cmp(expected / p, actual / p, shallow=False)]
    return diffs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="compare a fresh regeneration with --out")
    args = parser.parse_args(argv)
    if args.check:
        with tempfile.TemporaryDirectory() as temp:
            write(Path(temp))
            diffs = differences(Path(temp), args.out)
        for line in diffs:
            print(line)
        print("release vectors: byte-identical" if not diffs else f"release vectors: {len(diffs)} differences")
        return 1 if diffs else 0
    world = write(args.out)
    print(f"wrote {len(world.files)} files and {len(world.cases)} cases to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
