#!/usr/bin/env python3
"""Regenerate the SDUI golden documents under Tests/Fixtures/release-bundles/ui/ (CORE-PHASES.md P7a).

    python3 scripts/release/make_ui_vectors.py [--out DIR]   write ui/documents/, ui/vectors.json and ui/fuzz.json
    python3 scripts/release/make_ui_vectors.py --check       regenerate in a temp dir and compare byte for byte

Each case's expected verdict is declared in ui_cases.py and must equal the reference decoder (ui_reference.py), or
generation fails. fuzz.json is the shared deterministic fuzz: seed, iteration count and the reference verdict of
every mutated document, which the Swift fuzz test replays and must match. The script owns only ui/.
"""

import argparse
import filecmp
import json
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import ui_fuzz  # noqa: E402
import ui_reference as ref  # noqa: E402
from ui_cases import HOSTS, cases  # noqa: E402

ROOT = HERE.parents[1]
DEFAULT_OUT = ROOT / "Tests/Fixtures/release-bundles"
FUZZ_SEED = 2026102007
FUZZ_ITERATIONS = 2000


def document_bytes(document):
    if isinstance(document, bytes):
        return document
    return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def build():
    files, entries = {}, []
    for case_id, description, document, view, expect, overrides in cases():
        # Raw-byte cases are deliberately not JSON; other fixture tests read every *.json with the stdlib parser.
        rel = f"documents/{case_id}.{'bytes' if isinstance(document, bytes) else 'json'}"
        files[rel] = document_bytes(document)
        verdict, _, reason = expect.partition("/")
        inputs = {"document": rel, "view": view, "killed": overrides.get("killed", []),
                  "url_hosts": overrides.get("url_hosts", HOSTS),
                  "limits": dict(ref.LIMITS, **overrides.get("limits", {}))}
        expected = {"verdict": verdict, **({"reason": reason} if reason else {})}
        actual = ref.decode(files[rel], view, inputs["limits"], inputs["url_hosts"], inputs["killed"])
        if actual != expected:
            raise SystemExit(f"{case_id}: reference gives {actual}, case declares {expected}")
        entries.append({"id": case_id, "description": description, "inputs": inputs, "expect": expected})
    vectors = {"schema": "swarmhub/ui-vectors/1",
               "note": "Generated by scripts/release/make_ui_vectors.py. See docs/update-service/SCHEMAS.md §13.",
               "reasons": list(ref.REASONS), "cases": entries}
    files["vectors.json"] = (json.dumps(vectors, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode()
    files["fuzz.json"] = (json.dumps(fuzz(entries, files), indent=1, sort_keys=True) + "\n").encode()
    return files


def fuzz(entries, files, seed=FUZZ_SEED, iterations=FUZZ_ITERATIONS):
    """Replay of the shared mutator over every case document in order; one verdict label per iteration."""
    rng = ui_fuzz.SplitMix64(seed)
    expected = []
    for _ in range(iterations):
        entry = entries[rng.below(len(entries))]
        inputs = entry["inputs"]
        data = ui_fuzz.fuzz_document(files[inputs["document"]], rng)
        if data is None:
            expected.append("skip")
            continue
        verdict = ref.decode(data, inputs["view"], inputs["limits"], inputs["url_hosts"], inputs["killed"])
        expected.append(ui_fuzz.label(verdict))
    return {"schema": "swarmhub/ui-fuzz/1", "seed": seed, "iterations": iterations, "expected": expected}


def write(out):
    files = build()
    shutil.rmtree(out / "ui", ignore_errors=True)
    for rel, data in sorted(files.items()):
        path = out / "ui" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return files


def tree(directory):
    return sorted(str(p.relative_to(directory)) for p in (directory / "ui").rglob("*") if p.is_file())


def differences(expected, actual):
    left, right = tree(expected), tree(actual)
    diffs = [f"only in regenerated: {p}" for p in sorted(set(left) - set(right))]
    diffs += [f"only in fixtures: {p}" for p in sorted(set(right) - set(left))]
    diffs += [f"differs: {p}" for p in sorted(set(left) & set(right))
              if not filecmp.cmp(expected / p, actual / p, shallow=False)]
    return diffs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="compare a fresh regeneration with --out")
    args = parser.parse_args(argv)
    if args.check:
        with tempfile.TemporaryDirectory() as temp:
            write(Path(temp))
            diffs = differences(Path(temp), args.out)
        for line in diffs:
            print(line)
        print("ui vectors: byte-identical" if not diffs else f"ui vectors: {len(diffs)} differences")
        return 1 if diffs else 0
    files = write(args.out)
    print(f"wrote {len(files)} files under {args.out / 'ui'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
